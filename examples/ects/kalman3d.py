ssm0 = StateSpaceModel(
    z=np.eye(2),
    d=np.array([10.0, 0.0]),
    h=np.array([[2.0, 0.0], [0.0, 1.0]]),
    t=np.array([[0.5, 0.3], [0.0, 0.2]]),
    c=np.array([1.0, 4.0]),
    r=np.array([[1.0], [1.0]]),
    q=np.array([[1.0]]),
)
