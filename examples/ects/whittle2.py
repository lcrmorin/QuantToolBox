order = 4


def bloomfield_sdf(lam: np.ndarray, theta: np.ndarray) -> np.ndarray:
    gamma_ = theta[:order]
    sigma = theta[order]
    j = np.arange(1, order + 1)
    w = np.cos(np.outer(lam, j))
    sdf = (sigma**2) * np.exp(2 * w @ gamma_)
    return sdf / (2 * np.pi)


